def fill():
    po = polib.pofile("locale/en/LC_MESSAGES/django.po")
    filled = 0
    for entry in po:
        # Marca el archivo como traducido al inglés
        if not entry.msgstr and entry.msgid in TRANSLATIONS:
            entry.msgstr = TRANSLATIONS[entry.msgid]
            filled += 1
    # Borra el flag fuzzy del header
    if po.metadata_is_fuzzy:
        po.metadata_is_fuzzy = []
    po.metadata["Language"] = "en"
    po.metadata["Last-Translator"] = "Paws & Walks team"
    po.metadata["Language-Team"] = "English"
    po.save("locale/en/LC_MESSAGES/django.po")
    po.save_as_mofile("locale/en/LC_MESSAGES/django.mo")
    print(f"[OK] Filled {filled} English translations")
    print(f"[OK] Total entries: {len(po)}")
    print(f"[OK] Translated: {len([e for e in po if e.msgstr])}")
    print(f"[OK] Untranslated: {len([e for e in po if not e.msgstr])}")


if __name__ == "__main__":
    fill()
